    /** المنيو الظاهر في الموقع (من قاعدة البيانات) مع التقييمات المعتمدة */
    public static function forSite(): array
    {
        $out = [];
        $cats = Category::with([
            'items'         => fn ($q) => $q->where('active', true)->orderBy('sort')->orderBy('id'),
            'items.reviews' => fn ($q) => $q->where('approved', true)->latest(),
        ])->orderBy('sort')->orderBy('id')->get();

        foreach ($cats as $c) {
            if ($c->items->isEmpty()) {
                continue;
            }
            $out[$c->name] = $c->items->map(function ($i) use ($c) {
                $rev = $i->reviews;

                return [
                    'id'            => $i->id,
                    'name'          => $i->name,
                    'price'         => (float) $i->price,
                    'img'           => $i->image,
                    'desc'          => $i->description,
                    'details'       => $i->details,
                    'ingredients'   => $i->ingredients ? array_values(array_filter(preg_split('/\\s*[،,]\\s*/u', $i->ingredients))) : [],
                    'cat'           => $c->name,
                    'rating'        => $rev->count() ? round($rev->avg('rating'), 1) : null,
                    'reviews_count' => $rev->count(),
                    'reviews'       => $rev->take(10)->map(fn ($r) => [
                        'name' => $r->name, 'rating' => (int) $r->rating,
                        'comment' => $r->comment, 'date' => $r->created_at->format('Y-m-d'),
                    ])->values()->all(),
                ];
            })->all();
        }
        return $out;
    }

    /** id => [name, price] — المصدر الوحيد للأسعار عند الطلب */
    public static function catalog(): array
    {
        return MenuItem::where('active', true)->get()
            ->mapWithKeys(fn ($i) => [$i->id => ['name' => $i->name, 'price' => (float) $i->price]])
            ->all();
    }
